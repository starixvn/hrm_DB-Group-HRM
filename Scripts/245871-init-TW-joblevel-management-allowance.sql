-- Update theo dữ liệu từ bảng tmp
UPDATE ce
SET 
    ce.JobLevelId = jl.JobLevelId
FROM CompanyEmployee ce
INNER JOIN Employee e ON ce.UserId = e.UserId
INNER JOIN #Tmp t ON t.CtrId = e.CtrId
INNER JOIN JobLevel jl ON jl.Name = t.JobLevel
WHERE t.JobLevel IS NOT NULL AND t.JobLevel <> '';
GO

-- Delete và Insert Management Allowance vào EmployeePayrollAllowance
-- Xóa các record Management Allowance cũ có ItemName khớp với ManagementAllowance trong bảng tmp
DELETE epa
FROM EmployeePayrollAllowance epa
INNER JOIN AllowanceItemSetting ais ON epa.AllowanceItemSettingId = ais.AllowanceItemSettingId
INNER JOIN PayrollItemSetting pis ON ais.PayrollItemSettingId = pis.PayrollItemSettingId
INNER JOIN CompanyEmployee ce ON epa.EmpId = ce.EmpId
INNER JOIN Employee e ON ce.UserId = e.UserId
INNER JOIN #Tmp t ON t.CtrId = e.CtrId
INNER JOIN Company c ON c.Name = t.CompanyName AND c.CompanyId = ce.CompanyId
WHERE pis.Type = 'Management Allowance'
    AND pis.CompanyId = c.CompanyId
    AND ais.ItemName = t.ManagementAllowance
    AND t.ManagementAllowance IS NOT NULL 
    AND t.ManagementAllowance <> '';
GO

-- Insert Management Allowance mới
INSERT INTO EmployeePayrollAllowance (EmpId, AllowanceItemSettingId)
SELECT 
    ce.EmpId,
    ais.AllowanceItemSettingId
FROM #Tmp t
INNER JOIN Employee e ON t.CtrId = e.CtrId
INNER JOIN CompanyEmployee ce ON ce.UserId = e.UserId
INNER JOIN Company c ON c.Name = t.CompanyName AND c.CompanyId = ce.CompanyId
INNER JOIN PayrollItemSetting pis ON pis.CompanyId = c.CompanyId 
    AND pis.Type = 'Management Allowance'
    AND ISNULL(pis.IsDeleted, 0) = 0
INNER JOIN AllowanceItemSetting ais ON ais.PayrollItemSettingId = pis.PayrollItemSettingId
    AND ais.ItemName = t.ManagementAllowance
    AND ISNULL(ais.IsDeleted, 0) = 0
WHERE t.ManagementAllowance IS NOT NULL 
    AND t.ManagementAllowance <> '';
GO

